#!/usr/bin/env node
// build.js — evaluate the catalogue into the language-neutral spec.json.
//
//   node spec/build.js           write spec/spec.json and the copies shipped by the packages
//   node spec/build.js --check   recompute and compare with the committed spec.json
//
// spec.json is the contract shared by every implementation: gauge recipes (+ the
// fingerprints their builders must reproduce), the operations, the measures, the frozen
// reference values and the tolerances. Only this directory knows how the references are
// derived; the packages and the bindings read spec.json alone.
//
// --check compares numbers to 1e-12 relative, not bit for bit: references and
// fingerprints go through libm (Math.sin, Math.acos…), which may differ in the last bit
// between platforms and Node versions.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { GAUGES, CASES } from './catalogue.js';
import { fingerprint } from '../js/src/gauges.js';
import { ARRAY_MEASURES } from '../js/src/measures.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
export const SPEC_VERSION = '1.0.0';

// ── tiers (SPEC.md, Tiers) ────────────────────────────────────────────────────
// core       parameters of an unprocessed gauge: anything that can read the gauge can run it
// operators  standard operations (levelling, filtering, masking, geometry…) measured on the array
// extension  non-standard parameters, implementation-specific operations and analysis outputs
const STANDARD_OPS = new Set(['level', 'detrend', 'levelPoints', 'levelTLS', 'removeSphere', 'removeCylinder', 'filter',
  'center', 'zero', 'invert', 'threshold', 'removeOutliers', 'fill', 'crop', 'zoom', 'rotate',
  'maskRect', 'maskCircle', 'maskThreshold', 'maskInvert', 'maskToNaN']);
const NON_STANDARD_PARAMS = new Set(['period']);

function tierOf(c) {
  const m = c.measure, standardParam = m.kind === 'param' && !NON_STANDARD_PARAMS.has(m.name);
  if (!c.ops.length && standardParam) return 'core';
  if (c.ops.every(o => STANDARD_OPS.has(o.op)) && (standardParam || ARRAY_MEASURES.has(m.kind))) return 'operators';
  return 'extension';
}

const finite = (v) => (typeof v === 'number' && !Number.isFinite(v) ? null : v);

export function buildSpec() {
  const gauges = {};
  for (const [id, g] of Object.entries(GAUGES)) gauges[id] = { ...g, fingerprint: fingerprint(g) };
  const ids = new Set();
  for (const c of CASES) {
    if (ids.has(c.id)) throw new Error(`duplicate case id ${c.id}`);
    ids.add(c.id);
    if (!gauges[c.gauge]) throw new Error(`case ${c.id}: unknown gauge ${c.gauge}`);
    for (const r of [c.reference, c.discrete]) if (r && r.value != null && !Number.isFinite(r.value)) throw new Error(`case ${c.id}: non-finite reference`);
  }
  return {
    name: 'softgauge: analytic soft gauges for surface texture software',
    version: SPEC_VERSION,
    conventions: {
      units: 'lengths and heights in µm, material ratios in %, angles in degrees',
      grid: 'row-major; pixel (r, c) at x = c·dx, y = r·dy (row 0 first); samples are points, so n samples span (n − 1)·dx; crop/mask boxes and circles use y measured from the bottom: yb = (ny − 1 − r)·dy',
      judging: 'pass iff |value − ref| ≤ tol.abs + tol.rel·|ref|, where ref = discrete.value if present else reference.value; expectNaN cases pass iff the value is NaN/undefined',
      tiers: 'core = parameters of an unprocessed gauge; operators = standard operations measured on the array; extension = non-standard parameters, implementation-specific operations and analysis outputs',
    },
    gauges,
    cases: CASES.map(c => ({
      ...JSON.parse(JSON.stringify(c, (k, v) => finite(v))),
      tier: tierOf(c),
      domain: gauges[c.gauge].profile ? 'profile' : 'areal',
    })),
  };
}

/** Max relative difference between two JSON trees (Infinity if their structure differs). */
function diff(a, b, path = '') {
  if (typeof a === 'number' && typeof b === 'number') return a === b ? 0 : Math.abs(a - b) / Math.max(Math.abs(a), Math.abs(b), 1e-300);
  if (a === null || b === null || typeof a !== 'object' || typeof b !== 'object') {
    if (a !== b) throw new Error(`spec differs at ${path || '/'}: ${JSON.stringify(a)} ≠ ${JSON.stringify(b)}`);
    return 0;
  }
  const ka = Object.keys(a), kb = Object.keys(b);
  if (ka.length !== kb.length || ka.some((k, i) => k !== kb[i])) throw new Error(`spec differs at ${path || '/'}: keys`);
  let d = 0;
  for (const k of ka) d = Math.max(d, diff(a[k], b[k], `${path}/${k}`));
  return d;
}

const asModule = (text) => `// Generated by spec/build.js from spec/spec.json — do not edit.\nexport default ${text.trimEnd()};\n`;

const OUT = {
  json: join(here, 'spec.json'),
  js: join(root, 'js/src/spec-data.js'),
  py: join(root, 'python/src/softgauge/spec.json'),
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const spec = buildSpec(), text = JSON.stringify(spec, null, 1) + '\n';
  if (process.argv.includes('--check')) {
    const committed = JSON.parse(readFileSync(OUT.json, 'utf8'));
    const d = diff(JSON.parse(text), committed);
    if (d > 1e-12) throw new Error(`spec.json is out of date (max relative difference ${d.toExponential(2)}); run node spec/build.js`);
    const json = readFileSync(OUT.json, 'utf8');
    if (readFileSync(OUT.py, 'utf8') !== json) throw new Error(`${OUT.py} is not a copy of spec/spec.json`);
    if (readFileSync(OUT.js, 'utf8') !== asModule(json)) throw new Error(`${OUT.js} is not generated from spec/spec.json`);
    console.log(`spec.json up to date (max relative difference ${d.toExponential(2)})`);
  } else {
    writeFileSync(OUT.json, text);
    writeFileSync(OUT.py, text);
    writeFileSync(OUT.js, asModule(text));
    const tiers = {};
    for (const c of spec.cases) tiers[c.tier] = (tiers[c.tier] || 0) + 1;
    console.log(`spec ${spec.version}: ${Object.keys(spec.gauges).length} gauges, ${spec.cases.length} cases (${Object.entries(tiers).map(([k, v]) => `${v} ${k}`).join(', ')})`);
  }
}
